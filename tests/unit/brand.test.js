import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';

// The brand is lowercase everywhere, and no AI credit appears in anything a visitor or reader sees.
function walk(dir, out = []) {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    if (['node_modules', 'dist', '.git', 'test-results', 'textures', 'stills'].includes(f.name)) continue;
    const p = path.join(dir, f.name);
    if (f.isDirectory()) walk(p, out); else if (/\.(js|jsx|css|html|md|json|glsl|svg)$/.test(f.name) && f.name !== 'package-lock.json' && !p.includes('tests/unit/brand') && !p.includes('tests/e2e/journey')) out.push(p);
  }
  return out;
}

describe('brand rules', () => {
  const files = walk('.');
  it('never renders the name in anything but lowercase', () => {
    for (const f of files) expect(fs.readFileSync(f, 'utf8'), f).not.toMatch(/\bLiftoff\b|\bLIFTOFF\b|\bLiftOff\b|\bLift Off\b/);
  });
  it('carries no generated-by branding', () => {
    for (const f of files) expect(fs.readFileSync(f, 'utf8'), f).not.toMatch(/built with claude|generated by ai|co-authored-by/i);
  });
  it('is JavaScript only', () => {
    const ts = walk('src').concat(walk('tests')).filter((f) => /\.tsx?$/.test(f));
    expect(ts).toEqual([]);
  });
});
